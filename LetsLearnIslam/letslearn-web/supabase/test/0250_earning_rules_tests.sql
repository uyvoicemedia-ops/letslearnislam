-- ============================================================
-- How coins are earned (0024, 0025): by rules the server applies. Runs after 0240.
-- Welcome, the register, marked homework, and the four claims a child can make.
-- ============================================================
do $$
declare
  sch uuid; c_q1 uuid; c_hifz uuid; c_b uuid;
  aisha uuid; hamza uuid; p1 uuid; p2 uuid; p3 uuid; np uuid; np2 uuid; npt uuid;
  mauluda uuid; mauluda_uid uuid; abdur_uid uuid; yusuf_uid uuid; ab_uid uuid; fatima_uid uuid; kid uuid; kid2 uuid; kidt uuid;
  b0 int; j jsonb; n int; i int; pr bigint; pr2 bigint; hw uuid; hw2 uuid; hw3 uuid; hw4 uuid; hw5 uuid; hw6 uuid; hw7 uuid; tot int; d date := current_date;
begin
  select id into sch from schools where name = 'Al-Noor Madrasah';
  select id into c_q1 from classes where join_code = 'QAIDA1';
  select id into c_hifz from classes where join_code = 'HIFZ01';
  select id into c_b from classes where join_code = 'OTHER1';
  select id into aisha from profiles where full_name = 'Aisha Khan';
  select id into hamza from profiles where full_name = 'Hamza Malik';
  select id, auth_uid into mauluda, mauluda_uid from profiles where full_name = 'Mauluda Begum';
  select auth_uid into abdur_uid from profiles where full_name = 'Abdur Rahman';
  select auth_uid into yusuf_uid from profiles where full_name = 'Yusuf Ibrahim';
  select auth_uid into ab_uid from profiles where full_name = 'Admin B';
  select auth_uid into fatima_uid from profiles where full_name = 'Fatima Khan';
  select pupil_id into p1 from enrolments where class_id = c_q1 and pupil_id = aisha;
  select pupil_id into p2 from enrolments where class_id = c_q1 and pupil_id <> aisha order by pupil_id limit 1;
  select pupil_id into p3 from enrolments where class_id = c_q1 and pupil_id not in (aisha, p2) order by pupil_id limit 1;
  perform t_assert(p1 is not null and p2 is not null and p3 is not null, '(setup: three pupils in Qaida 1)');
  insert into auth.users (is_anonymous) values (true) returning id into kid;
  insert into auth.users (is_anonymous) values (true) returning id into kid2;
  update profiles set auth_uid = kid where id = aisha;
  update profiles set auth_uid = kid2 where id = hamza;
  delete from points where pupil_id in (aisha, hamza, p2, p3);

  raise notice 'a welcome, once, ever';
  insert into profiles (school_id, role, full_name, pin_hash) values (sch, 'student', 'Welcome Test One', 'x') returning id into np;
  insert into enrolments (class_id, pupil_id) values (c_q1, np);
  perform t_assert(ll_balance(np) = 100 and (select source from points where pupil_id = np) = 'welcome', 'joining a class pays a welcome of 100');
  insert into enrolments (class_id, pupil_id) values (c_hifz, np);
  delete from enrolments where pupil_id = np and class_id = c_q1;
  insert into enrolments (class_id, pupil_id) values (c_q1, np);
  perform t_assert(ll_balance(np) = 100, 'joining another class, or leaving and rejoining, pays nothing more');
  perform t_be(null); insert into profiles (school_id, role, full_name, pin_hash, is_test) values (sch, 'student', 'Welcome Test Student', 'x', true) returning id into npt;
  insert into enrolments (class_id, pupil_id) values (c_q1, npt);
  perform t_assert(ll_balance(npt) = 0, 'a test student gets none (theirs are the fake ones)');
  update reward_rates set coins = 40 where key = 'welcome';
  insert into profiles (school_id, role, full_name, pin_hash) values (sch, 'student', 'Welcome Test Two', 'x') returning id into np2;
  insert into enrolments (class_id, pupil_id) values (c_q1, np2);
  perform t_assert(ll_balance(np2) = 40, 'the amount comes from reward_rates');
  update reward_rates set coins = 100 where key = 'welcome';
  delete from enrolments where pupil_id in (np, np2, npt); delete from profiles where id in (np, np2, npt);

  raise notice 'the register, paid when the teacher finishes it';
  delete from attendance where class_id = c_q1 and on_date in (d, d - 1, d + 1);
  insert into attendance (pupil_id, class_id, on_date, mark) values (p1, c_q1, d, 'present'), (p2, c_q1, d, 'late'), (p3, c_q1, d, 'absent');
  perform t_assert(ll_balance(p1) = 0 and ll_balance(p2) = 0, 'marking the register pays nothing by itself (no coins for toggling a mark)');
  perform t_be(mauluda_uid); set local role authenticated;
  perform t_assert((attendance_set_camera(c_q1, p1, d, true) ->> 'ok')::boolean and (attendance_set_camera(c_q1, p2, d, true) ->> 'ok')::boolean, 'the teacher ticks camera-on for two children');
  perform t_assert((attendance_set_camera(c_q1, p3, d, true) ->> 'error') = 'not_marked_here', 'but not for a child marked absent');
  perform t_assert((attendance_set_camera(c_q1, hamza, d, true) ->> 'error') = 'not_in_class', 'nor for a child not in the class');
  perform t_assert((attendance_set_camera(c_q1, p1, d, null) ->> 'error') = 'bad_value', 'null is refused');
  j := register_finish(c_q1, d);
  reset role;
  perform t_assert((j ->> 'ok')::boolean and (j ->> 'children')::int = 2 and (j ->> 'coins')::int = 30, 'finishing the register pays: 20 (here 5, on time 10, camera 5) + 10 (here 5, camera 5) = 30');
  perform t_assert(ll_balance(p1) = 20 and ll_balance(p2) = 10 and ll_balance(p3) = 0, 'on time pays more than late, and absent pays nothing');
  perform t_be(mauluda_uid); set local role authenticated; j := register_finish(c_q1, d); reset role;
  perform t_assert((j ->> 'coins')::int = 0 and ll_balance(p1) = 20, 'pressing it again pays nothing');
  update attendance set mark = 'present' where pupil_id = p2 and on_date = d;
  perform t_be(mauluda_uid); set local role authenticated; j := register_finish(c_q1, d); reset role;
  perform t_assert((j ->> 'coins')::int = 10 and ll_balance(p2) = 20, 'a late correction pays only the part that is new (on time: 10)');
  update attendance set mark = 'absent' where pupil_id = p1 and on_date = d;
  perform t_be(mauluda_uid); set local role authenticated; j := register_finish(c_q1, d); reset role;
  perform t_assert(ll_balance(p1) = 20, 'and a mark changed to absent afterwards takes nothing back');
  perform t_assert((select count(*) from points where source = 'attendance' and amount <= 0) = 0, 'the register never writes a non-positive entry');
  perform t_be(mauluda_uid); set local role authenticated;
  perform t_assert((register_finish(c_q1, d + 1) ->> 'error') = 'bad_date' and (register_finish(c_q1, d - 2) ->> 'error') = 'bad_date' and (register_finish(c_q1, null) ->> 'error') = 'bad_date', 'a future date, last week, and null are refused');
  perform t_assert((register_finish(c_q1, d - 1) ->> 'ok')::boolean, 'yesterday is allowed (a register finished the next morning)');
  reset role;
  perform t_be(abdur_uid); set local role authenticated;
  perform t_assert((register_finish(c_q1, d) ->> 'error') = 'not_allowed' and (attendance_set_camera(c_q1, p1, d, true) ->> 'error') = 'not_allowed', 'a teacher of another class cannot');
  reset role; perform t_be(ab_uid); set local role authenticated;
  perform t_assert((register_finish(c_q1, d) ->> 'error') = 'not_allowed', 'nor an admin at another school');
  reset role; perform t_be(fatima_uid); set local role authenticated;
  perform t_assert((register_finish(c_q1, d) ->> 'error') = 'not_allowed', 'nor a parent');
  reset role; perform t_be(kid); set local role authenticated;
  perform t_assert((register_finish(c_q1, d) ->> 'error') = 'not_allowed', 'nor a child');
  reset role; perform t_be(null); set local role anon;
  perform t_assert(t_say(format('select register_finish(%L, %L)', c_q1, d)) like '42501%', 'nor a visitor');
  reset role; perform t_be(yusuf_uid); set local role authenticated;
  perform t_assert((register_finish(c_q1, d) ->> 'ok')::boolean, 'an admin of the school can');
  reset role;
  delete from attendance where class_id = c_q1 and on_date in (d, d - 1);

  raise notice 'marked homework pays the child';
  delete from points where pupil_id in (aisha, hamza, p2, p3);
  perform t_be(mauluda_uid); set local role authenticated;
  hw := (homework_set(c_q1, 'Pay test A', null, null, d + 3) ->> 'id')::uuid; hw2 := (homework_set(c_q1, 'Pay test B', null, null, d + 3) ->> 'id')::uuid;
  hw3 := (homework_set(c_q1, 'Pay test C', null, null, d + 3) ->> 'id')::uuid; hw4 := (homework_set(c_q1, 'Pay test D', null, null, d + 3) ->> 'id')::uuid;
  hw5 := (homework_set(c_q1, 'Pay test E', null, null, d + 3) ->> 'id')::uuid; hw6 := (homework_set(c_q1, 'Pay test F', null, null, d + 3) ->> 'id')::uuid;
  reset role;
  insert into submissions (homework_id, pupil_id, score) select h, aisha, 70 from unnest(array[hw, hw2, hw3, hw4, hw5, hw6]) h;
  perform t_assert(ll_balance(aisha) = 0, 'handing homework in pays nothing; only the teacher marking it does');
  perform t_be(mauluda_uid); set local role authenticated;
  perform homework_mark(hw, aisha, 85, 'great');
  reset role;
  perform t_assert(ll_balance(aisha) = 15, 'marked 85: 15 coins');
  perform t_be(mauluda_uid); set local role authenticated; perform homework_mark(hw, aisha, 85, 'again'); perform homework_mark(hw, aisha, 100, 'higher'); reset role;
  perform t_assert(ll_balance(aisha) = 15, 're-marking the same piece pays nothing more');
  perform t_be(mauluda_uid); set local role authenticated; perform homework_mark(hw2, aisha, 60, null); reset role;
  perform t_assert(ll_balance(aisha) = 25, 'marked 60: 10 coins');
  perform t_be(mauluda_uid); set local role authenticated; perform homework_mark(hw3, aisha, 20, null); reset role;
  perform t_assert(ll_balance(aisha) = 30, 'marked 20: 5 coins, so effort is acknowledged');
  perform t_be(mauluda_uid); set local role authenticated; perform homework_mark(hw4, aisha, 90, null); perform homework_mark(hw5, aisha, 90, null); reset role;
  perform t_assert(ll_balance(aisha) = 45, 'a day''s marked homework stops at 45 (15 + 10 + 5 + 15 = 45; the next one pays nothing)');
  perform t_be(mauluda_uid); set local role authenticated; perform homework_mark(hw6, aisha, 90, null); reset role;
  perform t_assert(ll_balance(aisha) = 45, 'the ceiling holds');
  perform t_assert((select count(*) from points where source = 'homework') = 4, 'one entry per piece that paid');
  perform t_be(abdur_uid); set local role authenticated;
  perform t_assert((homework_mark(hw, aisha, 100, null) ->> 'error') = 'not_allowed', 'a teacher of another class cannot mark it (and so cannot pay)');
  reset role;
  delete from submissions where homework_id in (hw, hw2, hw3, hw4, hw5, hw6); delete from homework where id in (hw, hw2, hw3, hw4, hw5, hw6);
  delete from points where pupil_id = aisha;

  raise notice 'practice: a claim, made hard to farm';
  insert into practice (pupil_id, module_id, score, stars) values (aisha, 'tracing', 90, 3) returning id into pr;
  perform t_be(kid); set local role authenticated;
  j := earn_practice(pr);
  reset role;
  perform t_assert((j ->> 'minted')::int = 10 and ll_balance(aisha) = 10, 'a good practice (80+) pays 10');
  perform t_be(kid); set local role authenticated; j := earn_practice(pr); reset role;
  perform t_assert((j ->> 'error') = 'too_fast' and ll_balance(aisha) = 10, 'asking again straight away pays nothing');
  update points set at = now() - interval '2 minutes' where pupil_id = aisha;
  perform t_be(kid); set local role authenticated; j := earn_practice(pr); reset role;
  perform t_assert((j ->> 'minted')::int = 0 and ll_balance(aisha) = 10, 'the same practice can never be paid twice, even after the wait');
  insert into practice (pupil_id, module_id, score, stars) values (aisha, 'mazes', 60, 1) returning id into pr2;
  perform t_be(kid); set local role authenticated; j := earn_practice(pr2); reset role;
  perform t_assert((j ->> 'minted')::int = 6, 'a middling one (50 to 79) pays 6');
  update points set at = now() - interval '2 minutes' where pupil_id = aisha;
  insert into practice (pupil_id, module_id, score, stars) values (aisha, 'mazes', 20, 0) returning id into pr2;
  perform t_be(kid); set local role authenticated; j := earn_practice(pr2); reset role;
  perform t_assert((j ->> 'minted')::int = 3, 'and a first try, 3');
  insert into practice (pupil_id, module_id, score, stars) values (hamza, 'tracing', 90, 3) returning id into pr2;
  update points set at = now() - interval '2 minutes' where pupil_id = aisha;
  perform t_be(kid); set local role authenticated; j := earn_practice(pr2); reset role;
  perform t_assert((j ->> 'error') = 'no_such_practice' and ll_balance(aisha) = 19, 'a classmate''s practice cannot be claimed');
  perform t_be(kid); set local role authenticated; perform t_assert((earn_practice(-1) ->> 'error') = 'no_such_practice' and (earn_practice(null) ->> 'error') = 'no_such_practice', 'nor one that does not exist'); reset role;
  insert into practice (pupil_id, module_id, score, stars, at) values (aisha, 'tracing', 90, 3, now() - interval '20 minutes') returning id into pr2;
  perform t_be(kid); set local role authenticated; j := earn_practice(pr2); reset role;
  perform t_assert((j ->> 'error') = 'too_old', 'a practice more than 15 minutes old cannot be claimed (no saving them up)');
  perform t_be(mauluda_uid); set local role authenticated;
  perform t_assert((earn_practice(pr) ->> 'error') = 'not_allowed' and (earn_dhikr(1) ->> 'error') = 'not_allowed' and (earn_salah('fajr') ->> 'error') = 'not_allowed' and (earn_reading('x') ->> 'error') = 'not_allowed', 'a teacher cannot claim for anyone');
  reset role; perform t_be(null); set local role anon;
  perform t_assert(t_say('select earn_practice(1)') like '42501%' and t_say('select earn_dhikr(1)') like '42501%' and t_say($q$select earn_salah('fajr')$q$) like '42501%' and t_say($q$select earn_reading('x')$q$) like '42501%', 'a visitor cannot call any of them');
  reset role;
  delete from points where pupil_id in (aisha, hamza); delete from practice where pupil_id in (aisha, hamza);
  perform t_be(null); update profiles set is_test = true where id = aisha; insert into practice (pupil_id, module_id, score, stars) values (aisha, 'tracing', 90, 3) returning id into pr;
  perform t_be(kid); set local role authenticated;
  perform t_assert((earn_practice(pr) ->> 'error') = 'not_allowed' and (earn_dhikr(1) ->> 'error') = 'not_allowed' and (earn_salah('fajr') ->> 'error') = 'not_allowed', 'a test student earns nothing on the server');
  reset role; perform t_be(null); update profiles set is_test = false where id = aisha;
  delete from practice where pupil_id = aisha;

  raise notice 'dhikr, prayer and reading, and the one ceiling they share';
  delete from points where pupil_id = aisha;
  perform t_be(kid); set local role authenticated;
  perform t_assert((earn_dhikr(2) ->> 'error') = 'out_of_order' and (earn_dhikr(0) ->> 'error') = 'bad_set' and (earn_dhikr(4) ->> 'error') = 'bad_set' and (earn_dhikr(null) ->> 'error') = 'bad_set', 'sets come in order, and only 1 to 3');
  j := earn_dhikr(1);
  perform t_assert((j ->> 'minted')::int = 10, 'the first set pays 10');
  perform t_assert((earn_dhikr(1) ->> 'already')::boolean and (earn_dhikr(2) ->> 'error') = 'too_fast', 'the same set again pays nothing, and the next must wait a minute (thirty-three takes longer)');
  reset role;
  update points set at = now() - interval '2 minutes' where pupil_id = aisha;
  perform t_be(kid); set local role authenticated; j := earn_dhikr(2); reset role;
  perform t_assert((j ->> 'minted')::int = 10 and ll_balance(aisha) = 20, 'the second pays');
  update points set at = now() - interval '2 minutes' where pupil_id = aisha;
  perform t_be(kid); set local role authenticated; j := earn_dhikr(3); reset role;
  perform t_assert((j ->> 'minted')::int = 10 and ll_balance(aisha) = 30, 'and the third, and that is all for the day (a fourth set is refused)');
  perform t_be(kid); set local role authenticated;
  j := earn_salah('fajr');
  reset role;
  perform t_assert((j ->> 'minted')::int = 6 and ll_balance(aisha) = 36, 'a prayer pays 6');
  perform t_be(kid); set local role authenticated; j := earn_salah('fajr'); reset role;
  perform t_assert((j ->> 'minted')::int = 0 and ll_balance(aisha) = 36, 'once a day');
  perform t_be(kid); set local role authenticated;
  perform t_assert((earn_salah('lunch') ->> 'error') = 'bad_prayer' and (earn_salah(null) ->> 'error') = 'bad_prayer', 'only the five');
  j := earn_salah('dhuhr');
  reset role;
  perform t_assert((j ->> 'minted')::int = 4 and ll_balance(aisha) = 40, 'the daily ceiling of 40 cuts the next one short (4, not 6)');
  perform t_be(kid); set local role authenticated; j := earn_salah('asr'); reset role;
  perform t_assert((j ->> 'minted')::int = 0 and ll_balance(aisha) = 40, 'and then nothing more today, from any of them');
  perform t_assert((select coalesce(sum(amount), 0) from points where pupil_id = aisha and source in ('practice', 'reading', 'dhikr', 'salah')) = 40, 'practice, reading, dhikr and prayer together never pass 40 in a day');
  insert into practice (pupil_id, module_id, score, stars) values (aisha, 'tracing', 90, 3) returning id into pr;
  update points set at = now() - interval '2 minutes' where pupil_id = aisha;
  perform t_be(kid); set local role authenticated; j := earn_practice(pr); reset role;
  perform t_assert((j ->> 'minted')::int = 0 and (j ->> 'capped')::boolean, 'practice is capped by the same ceiling, and says so');
  insert into reading (pupil_id, book_id, page, updated_at) values (aisha, 'cap-book', 8, now()) on conflict (pupil_id, book_id) do update set page = 8, updated_at = now();
  perform t_be(kid); set local role authenticated; j := earn_reading('cap-book'); reset role;
  perform t_assert((j ->> 'minted')::int = 0 and ll_balance(aisha) = 40, 'and so is reading');
  perform t_assert((select coalesce(sum(amount), 0) from points where pupil_id = aisha and source = 'attendance') = 0, '(register coins are not part of that ceiling)');
  perform ll_mint(aisha, 'attendance', 15, 'reg:ceiling-test');
  perform t_assert(ll_balance(aisha) = 55, 'a teacher''s register can still pay a child who hit the ceiling');

  raise notice 'reading';
  delete from points where pupil_id = aisha; delete from reading where pupil_id = aisha;
  perform t_be(kid); set local role authenticated;
  perform t_assert((earn_reading('no-such-book') ->> 'error') = 'no_reading' and (earn_reading('bad book!') ->> 'error') = 'bad_book' and (earn_reading(null) ->> 'error') = 'bad_book', 'no reading, or a bad book name, pays nothing');
  insert into reading (pupil_id, book_id, page, updated_at) values (ll_me(), 'islam-1', 2, now());
  perform t_assert((earn_reading('islam-1') ->> 'error') = 'no_reading', 'two pages is not a session');
  update reading set page = 6, updated_at = now() where pupil_id = ll_me() and book_id = 'islam-1';
  j := earn_reading('islam-1');
  reset role;
  perform t_assert((j ->> 'minted')::int = 15 and ll_balance(aisha) = 15, 'a recent session of three or more pages pays 15');
  perform t_be(kid); set local role authenticated; j := earn_reading('islam-1'); reset role;
  perform t_assert((j ->> 'minted')::int = 0 and ll_balance(aisha) = 15, 'once per book per day');
  update reading set updated_at = now() - interval '30 minutes' where pupil_id = aisha;
  delete from points where pupil_id = aisha;
  perform t_be(kid); set local role authenticated; j := earn_reading('islam-1'); reset role;
  perform t_assert((j ->> 'error') = 'too_old', 'reading that was last touched half an hour ago is not a session in progress');
  delete from reading where pupil_id = aisha;

  raise notice 'the plumbing';
  perform t_assert(not has_function_privilege('authenticated', 'll_mint_within(uuid,point_source,int,text,text,point_source[],int)', 'execute') and not has_function_privilege('authenticated', 'll_room(uuid,point_source[],int)', 'execute')
                   and not has_function_privilege('authenticated', 'll_rate(text)', 'execute') and not has_function_privilege('authenticated', 'll_child()', 'execute'), 'the internals are shut');
  perform t_assert(has_function_privilege('authenticated', 'earn_practice(bigint)', 'execute') and not has_function_privilege('anon', 'earn_practice(bigint)', 'execute')
                   and not has_function_privilege('anon', 'register_finish(uuid,date)', 'execute') and not has_function_privilege('anon', 'attendance_set_camera(uuid,uuid,date,boolean)', 'execute'), 'the public ones are for signed-in people only');
  perform t_assert((select count(*) from pg_proc where proname in ('earn_practice', 'earn_dhikr', 'earn_salah', 'earn_reading', 'register_finish', 'attendance_set_camera', 'll_mint_within', 'll_room', 'll_rate', 'll_child', 'll_welcome', 'll_homework_paid')
                    and prosecdef and proconfig::text like '%search_path=public, pg_temp%') = 12, 'all twelve are security definer with a pinned search_path');
  perform t_assert((select count(*) from pg_trigger where tgname in ('ll_welcome', 'll_homework_paid') and not tgisinternal) = 2, 'the welcome and the homework payment are triggers the teacher or child cannot skip');

  perform t_be(null);
  update profiles set auth_uid = null where id in (aisha, hamza);
  delete from auth.users where id in (kid, kid2);
  delete from points where pupil_id in (aisha, hamza, p1, p2, p3);
  delete from attendance where class_id = c_q1 and on_date in (d, d - 1);
end $$;
