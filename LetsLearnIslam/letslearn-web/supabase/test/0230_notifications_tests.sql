-- ============================================================
-- Parent emails (0021): three yeses, a small message, a safe sender. Runs after 0220.
-- The negative tests matter most: who must NOT be emailed, what must NOT be in it.
-- ============================================================
do $$
declare
  sch uuid; schb uuid; c_q1 uuid; c_hifz uuid;
  aisha uuid; hamza uuid; fatima uuid; mauluda uuid; abdur uuid; yusuf uuid; adminb uuid; teacherb uuid;
  aisha_uid uuid; fatima_uid uuid; mauluda_uid uuid; abdur_uid uuid; yusuf_uid uuid; ab_uid uuid; tb_uid uuid; kid_uid uuid;
  j jsonb; n int; r record; t text; tok text; hw jsonb; sid uuid; lp uuid; lp_uid uuid; fee uuid; i int;
begin
  select id into sch from schools where name = 'Al-Noor Madrasah';
  select school_id into schb from profiles where full_name = 'Admin B';
  select id into c_q1 from classes where join_code = 'QAIDA1';
  select id into c_hifz from classes where join_code = 'HIFZ01';
  select id, auth_uid into aisha, aisha_uid from profiles where full_name = 'Aisha Khan';
  select id into hamza from profiles where full_name = 'Hamza Malik';
  select id, auth_uid into fatima, fatima_uid from profiles where full_name = 'Fatima Khan';
  select id, auth_uid into mauluda, mauluda_uid from profiles where full_name = 'Mauluda Begum';
  select id, auth_uid into abdur, abdur_uid from profiles where full_name = 'Abdur Rahman';
  select id, auth_uid into yusuf, yusuf_uid from profiles where full_name = 'Yusuf Ibrahim';
  select id, auth_uid into adminb, ab_uid from profiles where full_name = 'Admin B';
  select id, auth_uid into teacherb, tb_uid from profiles where full_name = 'Teacher B';
  delete from notify_outbox; delete from notify_prefs; delete from notify_school_settings;
  delete from attendance where pupil_id = aisha and on_date >= current_date - 5;

  raise notice 'silence is the default';
  delete from attendance where pupil_id = aisha and on_date = current_date; insert into attendance (pupil_id, class_id, on_date, mark) values (aisha, c_q1, current_date, 'absent');
  perform t_assert((select count(*) from notify_outbox) = 0, 'with nothing switched on, marking a child absent queues nothing');
  insert into notify_school_settings (school_id, enabled) values (sch, true);
  delete from attendance where pupil_id = aisha and on_date = current_date;
  delete from attendance where pupil_id = aisha and on_date = current_date; insert into attendance (pupil_id, class_id, on_date, mark) values (aisha, c_q1, current_date, 'absent');
  perform t_assert((select count(*) from notify_outbox) = 0, 'the school on, but the parent has not opted in: nothing');
  delete from attendance where pupil_id = aisha and on_date = current_date;
  update notify_school_settings set enabled = false where school_id = sch;
  insert into notify_prefs (parent_id, event, enabled) values (fatima, 'absence', true);
  delete from attendance where pupil_id = aisha and on_date = current_date; insert into attendance (pupil_id, class_id, on_date, mark) values (aisha, c_q1, current_date, 'absent');
  perform t_assert((select count(*) from notify_outbox) = 0, 'the parent opted in, but the school is off: nothing');
  delete from attendance where pupil_id = aisha and on_date = current_date;

  raise notice 'absence: all three yeses';
  update notify_school_settings set enabled = true where school_id = sch;
  delete from attendance where pupil_id = aisha and on_date = current_date; insert into attendance (pupil_id, class_id, on_date, mark) values (aisha, c_q1, current_date, 'absent');
  perform t_assert((select count(*) from notify_outbox) = 1, 'school on, parent opted in, confirmed address: one email is queued');
  select * into r from notify_outbox;
  perform t_assert(r.parent_id = fatima and r.event = 'absence' and r.state = 'queued', 'for the parent, as an absence, waiting');
  perform t_assert(r.subject = 'Aisha was marked absent', 'the subject uses the first name only');
  perform t_assert(r.body not like '%Khan%' and r.body like '%Aisha%' and r.body like '%Qaida 1%', 'the body says first name and class, never the surname');
  perform t_assert((r.subject || r.body) !~* '(@|https?://|score|coins|pin)', 'and no address, link, score, coin or PIN');
  update attendance set mark = 'present' where pupil_id = aisha and on_date = current_date;
  update attendance set mark = 'absent' where pupil_id = aisha and on_date = current_date;
  perform t_assert((select count(*) from notify_outbox) = 1, 'flipping the mark back and forth does not email twice for the same day');
  insert into attendance (pupil_id, class_id, on_date, mark) values (aisha, c_q1, current_date - 1, 'absent');
  perform t_assert((select count(*) from notify_outbox) = 2, 'a different day is a different email');
  insert into attendance (pupil_id, class_id, on_date, mark) values (aisha, c_q1, current_date - 4, 'absent');
  perform t_assert((select count(*) from notify_outbox) = 2, 'a register entry for last week is not news: no email');
  insert into attendance (pupil_id, class_id, on_date, mark) values (aisha, c_q1, current_date - 2, 'late'), (aisha, c_q1, current_date - 3, 'present');
  perform t_assert((select count(*) from notify_outbox) = 2, 'late and present do not email');
  perform t_assert((select count(*) from notify_outbox where parent_id <> fatima) = 0, 'and nobody else was told (no other parent, no teacher, no admin)');
  delete from attendance where pupil_id = aisha and on_date >= current_date - 5;

  raise notice 'homework and online lessons';
  delete from notify_outbox;
  insert into notify_prefs (parent_id, event, enabled) values (fatima, 'homework', true);
  perform t_be(mauluda_uid); set local role authenticated;
  hw := homework_set(c_q1, 'Trace alif, see https://evil.example/x?token=abc for help ' || repeat('x', 60), null, null, current_date + 3);
  reset role;
  perform t_assert((hw ->> 'ok')::boolean, 'a teacher sets homework as before');
  select * into r from notify_outbox where event = 'homework';
  perform t_assert(found and r.parent_id = fatima and r.subject = 'New homework for Qaida 1', 'the parent is told, once');
  perform t_assert(r.body not like '%evil.example%' and r.body like '%<link>%', 'a web address typed into a title is replaced');
  perform t_assert(length(r.body) < 250 and r.body like '%Trace alif%', 'and a long title is cut');
  insert into homework (class_id, title, due_on) values (c_q1, 'Old one', current_date - 2);    -- written by the owner: the function itself refuses a date in the past
  perform t_assert((select count(*) from notify_outbox where event = 'homework') = 1, 'homework already past its date does not email');
  insert into notify_prefs (parent_id, event, enabled) values (fatima, 'session', true);
  insert into class_sessions (class_id, title, starts_at, ends_at, link) values (c_q1, 'Qaida live', now() + interval '2 days', now() + interval '2 days 1 hour', 'https://zoom.us/j/12345');
  select * into r from notify_outbox where event = 'session';
  perform t_assert(found and r.subject = 'An online lesson for Qaida 1', 'an online lesson is announced');
  perform t_assert(r.body not like '%zoom%' and r.body not like '%http%' and r.body like '%Open the app to join%', 'WITHOUT its meeting link');
  insert into class_sessions (class_id, title, starts_at, ends_at) values (c_q1, 'Yesterday', now() - interval '1 day', now() - interval '23 hours');
  perform t_assert((select count(*) from notify_outbox where event = 'session') = 1, 'a lesson already in the past does not');

  raise notice 'fees';
  insert into notify_prefs (parent_id, event, enabled) values (fatima, 'fees', true);
  insert into fee_charges (school_id, payer_id, pupil_id, amount_pence, period, charge_date, status)
    values (sch, fatima, aisha, 1250, 'Autumn 2026', current_date + 5, 'pending') returning id into fee;
  select * into r from notify_outbox where event = 'fees';
  perform t_assert(found and r.subject = 'A fee is due' and r.body like '%£12.50%' and r.body like '%Autumn 2026%', 'a new fee names the amount and the period');
  perform t_assert((r.subject || r.body) !~* '(sort code|account|iban|mandate|gocardless)', 'and no bank detail');
  update fee_charges set status = 'failed' where id = fee;
  perform t_assert((select count(*) from notify_outbox where event = 'fees') = 2 and exists (select 1 from notify_outbox where subject = 'A payment could not be collected'), 'a failed collection is a second, different email');
  update fee_charges set status = 'failed' where id = fee;
  perform t_assert((select count(*) from notify_outbox where event = 'fees') = 2, 'and not repeated');
  delete from fee_charges where id = fee;

  raise notice 'who must not be emailed';
  delete from notify_outbox;
  insert into notify_prefs (parent_id, event, enabled) values (adminb, 'absence', true) on conflict do nothing;
  perform t_assert((select count(*) from notify_prefs where parent_id = adminb) = 1, '(setup: someone else has opted in)');
  delete from attendance where pupil_id = aisha and on_date = current_date; insert into attendance (pupil_id, class_id, on_date, mark) values (aisha, c_q1, current_date, 'absent');
  perform t_assert((select count(*) from notify_outbox where parent_id = adminb) = 0, 'a person who is not the child''s parent is not told, even if they opted in');
  delete from attendance where pupil_id = aisha and on_date = current_date; delete from notify_outbox; delete from notify_prefs where parent_id = adminb;
  update notify_prefs set enabled = false where parent_id = fatima and event = 'absence';
  delete from attendance where pupil_id = aisha and on_date = current_date; insert into attendance (pupil_id, class_id, on_date, mark) values (aisha, c_q1, current_date, 'absent');
  perform t_assert((select count(*) from notify_outbox) = 0, 'a parent who switched this kind off is not told');
  delete from attendance where pupil_id = aisha and on_date = current_date;
  update notify_prefs set enabled = true where parent_id = fatima and event = 'absence';
  update auth.users set email_confirmed_at = null where id = fatima_uid;
  delete from attendance where pupil_id = aisha and on_date = current_date; insert into attendance (pupil_id, class_id, on_date, mark) values (aisha, c_q1, current_date, 'absent');
  perform t_assert((select count(*) from notify_outbox) = 0, 'an address that has not been confirmed is not emailed');
  delete from attendance where pupil_id = aisha and on_date = current_date;
  update auth.users set email_confirmed_at = now() where id = fatima_uid;
  update auth.users set email = 'someone-else@example.com' where id = fatima_uid;
  delete from attendance where pupil_id = aisha and on_date = current_date; insert into attendance (pupil_id, class_id, on_date, mark) values (aisha, c_q1, current_date, 'absent');
  perform t_assert((select count(*) from notify_outbox) = 0, 'nor one that no longer matches the sign-in account');
  delete from attendance where pupil_id = aisha and on_date = current_date;
  update auth.users set email = 'parent@example.com' where id = fatima_uid;
  update profiles set email = 'parent@example.com' where id = fatima;
  insert into attendance (pupil_id, class_id, on_date, mark) values (hamza, c_q1, current_date, 'absent');
  perform t_assert((select count(*) from notify_outbox) = 0, 'a parent is not told about a child who is not theirs');
  delete from attendance where pupil_id = hamza and on_date = current_date;

  raise notice 'at most eight a day, and quiet hours';
  delete from notify_outbox;
  perform t_be(mauluda_uid); set local role authenticated;
  for i in 1 .. 11 loop perform homework_set(c_q1, 'Cap test ' || i, null, null, current_date + 5); end loop;
  reset role;
  perform t_assert((select count(*) from notify_outbox where parent_id = fatima) = 8, 'a parent is emailed at most 8 times a day (11 pieces of homework, 8 emails)');
  select ll_notify_when() into r;
  perform t_assert(case when extract(hour from (now() at time zone 'Europe/London')) >= 7 and extract(hour from (now() at time zone 'Europe/London')) < 21
                        then abs(extract(epoch from (ll_notify_when() - now()))) < 2
                        else to_char(ll_notify_when() at time zone 'Europe/London', 'HH24:MI') = '07:30' and ll_notify_when() > now() end,
                   'send time is now by day, and 07:30 London if it is between 21:00 and 07:00');
  perform t_assert((select count(*) from notify_outbox where send_after < now() - interval '1 second') = 0, 'nothing is queued in the past');

  raise notice 'the parent''s own switches';
  delete from notify_outbox; delete from notify_prefs;
  perform t_be(fatima_uid); set local role authenticated;
  j := notify_prefs_get();
  reset role;
  perform t_assert(j ->> 'email' = 'p***@example.com' and (j ->> 'verified')::boolean and (j ->> 'school_enabled')::boolean, 'a parent sees their address masked, that it is confirmed, and that the school has emails on');
  perform t_assert(j #>> '{prefs,absence}' = 'false' and j #>> '{prefs,homework}' = 'false' and j #>> '{prefs,fees}' = 'false' and j #>> '{prefs,session}' = 'false', 'and everything starts OFF');
  perform t_be(fatima_uid); set local role authenticated;
  perform t_assert((notify_prefs_set('absence', true) ->> 'ok')::boolean, 'she switches absence on');
  j := notify_prefs_get();
  reset role;
  perform t_assert(j #>> '{prefs,absence}' = 'true' and j #>> '{prefs,homework}' = 'false', 'and only that');
  perform t_be(fatima_uid); set local role authenticated;
  perform t_assert((notify_prefs_set('test', true) ->> 'error') = 'bad_event' and (notify_prefs_set('nonsense', true) ->> 'error') = 'bad_event' and (notify_prefs_set('absence', null) ->> 'error') = 'bad_event', 'a made-up kind, "test" or a null is refused');
  perform t_assert(t_say($q$insert into notify_prefs (parent_id, event, enabled) values (gen_random_uuid(), 'absence', true)$q$) like '42501%', 'the table cannot be written directly');
  perform t_assert(t_say('update notify_prefs set enabled = true') like '42501%' and t_say('delete from notify_prefs') like '42501%', 'nor changed or deleted');
  reset role;
  perform t_be(mauluda_uid); set local role authenticated;
  perform t_assert((notify_prefs_set('absence', true) ->> 'error') = 'not_allowed' and (notify_prefs_get() ->> 'error') = 'not_allowed', 'a teacher cannot use the parent''s switches');
  reset role;
  perform t_be(yusuf_uid); set local role authenticated;
  perform t_assert((notify_prefs_set('absence', true) ->> 'error') = 'not_allowed', 'nor can an admin switch one on for a parent');
  perform t_assert(t_count('select 1 from notify_prefs') = 0, 'and an admin cannot read the parents'' choices');
  reset role;
  insert into auth.users (is_anonymous) values (true) returning id into kid_uid;
  update profiles set auth_uid = kid_uid where id = aisha;
  perform t_be(kid_uid); set local role authenticated;
  perform t_assert((notify_prefs_set('absence', true) ->> 'error') = 'not_allowed', 'a child''s session cannot');
  reset role;
  update profiles set auth_uid = aisha_uid where id = aisha; delete from auth.users where id = kid_uid;
  perform t_be(null); set local role anon;
  perform t_assert(t_say('select notify_prefs_get()') like '42501%' and t_say($q$select notify_prefs_set('absence', true)$q$) like '42501%', 'a signed-out visitor cannot call either');
  reset role;

  raise notice 'one-click unsubscribe';
  update notify_school_settings set enabled = true where school_id = sch;
  insert into notify_prefs (parent_id, event, enabled) values (fatima, 'absence', true), (fatima, 'homework', true) on conflict (parent_id, event) do update set enabled = true;
  delete from attendance where pupil_id = aisha and on_date = current_date; insert into attendance (pupil_id, class_id, on_date, mark) values (aisha, c_q1, current_date, 'absent');
  select unsub_token into tok from notify_outbox where event = 'absence' limit 1;
  perform t_assert(length(tok) = 64 and tok ~ '^[0-9a-f]+$', 'every email has a 64-character random token');
  perform t_be(null); set local role anon;
  j := notify_unsubscribe(tok);
  reset role;
  perform t_assert(j = jsonb_build_object('ok', true), 'it works with no sign-in');
  perform t_assert((select enabled from notify_prefs where parent_id = fatima and event = 'absence') = false, 'and switches THAT kind off');
  perform t_assert((select enabled from notify_prefs where parent_id = fatima and event = 'homework') = true, 'and only that kind');
  delete from attendance where pupil_id = aisha and on_date = current_date; delete from notify_outbox;
  delete from attendance where pupil_id = aisha and on_date = current_date; insert into attendance (pupil_id, class_id, on_date, mark) values (aisha, c_q1, current_date, 'absent');
  perform t_assert((select count(*) from notify_outbox) = 0, 'afterwards that kind no longer queues');
  perform t_be(null); set local role anon;
  perform t_assert(notify_unsubscribe('nonsense') = jsonb_build_object('ok', true) and notify_unsubscribe(repeat('a', 64)) = jsonb_build_object('ok', true) and notify_unsubscribe(null) = jsonb_build_object('ok', true), 'a bad token gets exactly the same answer as a good one');
  perform t_assert(t_say('select count(*) from notify_outbox') like '42501%', 'and a signed-out visitor cannot read the outbox to find tokens');
  reset role;
  perform t_assert((select count(*) from notify_prefs where parent_id = fatima and event = 'homework' and enabled) = 1, 'a bad token changed nothing');

  raise notice 'reading your own history, and only that';
  delete from notify_outbox; update notify_prefs set enabled = true where parent_id = fatima;
  delete from attendance where pupil_id = aisha and on_date = current_date; insert into attendance (pupil_id, class_id, on_date, mark) values (aisha, c_q1, current_date, 'absent');
  perform t_be(fatima_uid); set local role authenticated;
  perform t_assert(t_count('select 1 from notify_outbox') = 1, 'a parent reads their own email history');
  perform t_assert(t_say('select unsub_token from notify_outbox') like '42501%' and t_say('select body from notify_outbox') like '42501%', 'but not the unsubscribe token or the body column');
  perform t_assert(t_say($q$update notify_outbox set state = 'sent'$q$) like '42501%' and t_say('delete from notify_outbox') like '42501%' and t_say($q$insert into notify_outbox (school_id, parent_id, event, dedupe_key, subject, body) values (gen_random_uuid(), gen_random_uuid(), 'test', 'x', 'x', 'x')$q$) like '42501%', 'and cannot write it');
  reset role;
  perform t_be(yusuf_uid); set local role authenticated;
  perform t_assert(t_count('select 1 from notify_outbox') = 0, 'an admin cannot read parents'' mail');
  reset role;
  perform t_be(mauluda_uid); set local role authenticated;
  perform t_assert(t_count('select 1 from notify_outbox') = 0, 'nor can a teacher');
  reset role;
  perform t_be(null); set local role anon;
  perform t_assert(t_say('select 1 from notify_prefs') like '42501%' and t_say('select 1 from notify_school_settings') like '42501%', 'a signed-out visitor reads nothing');
  reset role;

  raise notice 'the admin''s switch';
  delete from notify_outbox; delete from notify_school_settings;
  perform t_be(mauluda_uid); set local role authenticated;
  perform t_assert((notify_school_set(true) ->> 'error') = 'not_allowed' and (notify_school_status() ->> 'error') = 'not_allowed' and (notify_send_test() ->> 'error') = 'not_allowed', 'a teacher cannot switch the school''s emails on, or read the status');
  reset role;
  perform t_be(fatima_uid); set local role authenticated;
  perform t_assert((notify_school_set(true) ->> 'error') = 'not_allowed', 'nor a parent');
  reset role;
  perform t_be(yusuf_uid); set local role authenticated;
  perform t_assert((notify_send_test() ->> 'error') = 'school_off', 'a test email waits until the school is switched on');
  perform t_assert((notify_school_set(true) ->> 'enabled')::boolean, 'an admin switches their school on');
  perform t_assert((notify_school_set(null) ->> 'error') = 'bad_value', 'null is refused');
  reset role;
  perform t_assert((select count(*) from notify_school_settings where school_id = sch and enabled and changed_by = yusuf) = 1 and (select count(*) from notify_school_settings where school_id = schb) = 0,
                   'it is recorded, with who, for their school only');
  perform t_be(ab_uid); set local role authenticated;
  perform t_assert((notify_school_status() ->> 'enabled')::boolean = false and t_count('select 1 from notify_school_settings') = 0, 'an admin at another school sees their own school as still off, and cannot see ours');
  reset role;
  perform t_be(yusuf_uid); set local role authenticated;
  perform t_assert((notify_send_test() ->> 'ok')::boolean, 'the test email goes to the admin''s own address');
  reset role;
  perform t_assert((select count(*) from notify_outbox where event = 'test' and parent_id = yusuf) = 1 and (select body from notify_outbox where event = 'test') not like '%Aisha%', 'and mentions no child');
  update auth.users set email_confirmed_at = null where id = yusuf_uid;
  perform t_be(yusuf_uid); set local role authenticated;
  perform t_assert((notify_send_test() ->> 'error') = 'email_not_confirmed', 'it refuses an admin whose own address is not confirmed');
  reset role;
  update auth.users set email_confirmed_at = now() where id = yusuf_uid;
  insert into notify_prefs (parent_id, event, enabled) values (fatima, 'absence', true) on conflict (parent_id, event) do update set enabled = true;
  delete from attendance where pupil_id = aisha and on_date = current_date; insert into attendance (pupil_id, class_id, on_date, mark) values (aisha, c_q1, current_date, 'absent');
  perform t_be(yusuf_uid); set local role authenticated;
  j := notify_school_status();
  reset role;
  perform t_assert((j #>> '{counts,queued}')::int >= 2 and (j #>> '{opted_in,absence}')::int >= 1, 'the status counts what is queued and how many parents opted in');
  perform t_assert(j::text !~* '(@|example\.com)', 'and holds no email address');
  perform t_be(yusuf_uid); set local role authenticated;
  perform notify_school_set(false);
  reset role;
  perform t_assert((select count(*) from notify_outbox where state = 'queued') = 0 and (select count(*) from notify_outbox where last_error = 'school_off') >= 2, 'switching the school off empties the queue at once');
  delete from attendance where pupil_id = aisha and on_date = current_date;

  raise notice 'the sender: claim, mark, and the checks made at the last moment';
  delete from notify_outbox; update notify_prefs set enabled = true where parent_id = fatima;
  perform t_be(yusuf_uid); set local role authenticated; perform notify_school_set(true); reset role;
  delete from attendance where pupil_id = aisha and on_date = current_date; insert into attendance (pupil_id, class_id, on_date, mark) values (aisha, c_q1, current_date, 'absent');
  update notify_outbox set send_after = now() - interval '1 minute';
  perform t_be(null);
  set local role authenticated;
  perform t_assert(t_say('select * from notify_claim_batch(10)') like '42501%' and t_say($q$select notify_mark(1, 'sent', null)$q$) like '42501%', 'a signed-in person cannot call the sender''s functions');
  reset role; set local role anon;
  perform t_assert(t_say('select * from notify_claim_batch(10)') like '42501%', 'nor a signed-out visitor');
  reset role;
  set local role service_role;
  select count(*) into n from notify_claim_batch(10);
  reset role;
  perform t_assert(n = 1, 'the service role claims the one due email');
  select * into r from notify_outbox;
  perform t_assert(r.state = 'sending' and r.attempts = 1 and r.claimed_at is not null, 'it is now marked as sending');
  set local role service_role; select count(*) into n from notify_claim_batch(10); reset role;
  perform t_assert(n = 0, 'a second claim does not hand out the same email again');
  set local role service_role;
  select * into r from notify_claim_batch(10);
  reset role;

  update notify_outbox set state = 'queued', attempts = 0, claimed_at = null where true;
  set local role service_role;
  select * into r from notify_claim_batch(10);
  reset role;
  perform t_assert(r.to_email = 'parent@example.com' and r.to_name = 'Fatima Khan' and r.subject = 'Aisha was marked absent' and length(r.unsub_token) = 64 and r.event = 'absence', 'a claimed row carries the address (only now), the name, the text and the token');
  set local role service_role; perform notify_mark(r.id, 'sent', null); reset role;
  perform t_assert((select state from notify_outbox where id = r.id) = 'sent' and (select sent_at from notify_outbox where id = r.id) is not null, 'marked sent');
  update notify_outbox set state = 'sending', attempts = 1, claimed_at = now() where id = r.id;
  set local role service_role; perform notify_mark(r.id, 'dry', null); reset role;
  perform t_assert((select state from notify_outbox where id = r.id) = 'dry', 'marked dry (nothing was actually sent)');
  update notify_outbox set state = 'sending', attempts = 2 where id = r.id;
  set local role service_role; perform notify_mark(r.id, 'retry', 'timeout talking to the provider'); reset role;
  perform t_assert((select state from notify_outbox where id = r.id) = 'queued' and (select send_after from notify_outbox where id = r.id) > now() + interval '19 minutes' and (select last_error from notify_outbox where id = r.id) like 'timeout%',
